"""NeMo-Skills RULER-v1 100-sample/task evaluation under KV compression.

This module consumes the tokenizer-specific JSONL files generated by NVIDIA's
RULER data preparation code.  It intentionally does *not* generate an easier
local approximation: the released ``input`` and ``answer_prefix`` fields are
concatenated verbatim, wrapped as the sole user message, and evaluated with the
13-task RULER-v1 task/scorer protocol.  The pinned NeMo-Skills adapter uses
100 examples per task; NVIDIA/RULER's canonical v1 shell config uses 500.
Consequently this module never labels its output a canonical full NVIDIA run.

Protocol sources audited for this implementation:

* NVIDIA/RULER commit ``38da79d79519ef87aa46ae804f838e1eab7f86d7``;
* NVIDIA-NeMo/Skills commit ``f4a3fd8e524acd9abd1fea4387e8f179f6d51cf3``.

The local ``ruler_multikey`` helper in :mod:`.longcontext` remains a synthetic
diagnostic and is deliberately separate from this evaluator.

Copyright 2025-2026 Fujitsu Ltd.
"""

