def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _task_file(data_root: str | Path, task: str) -> Path:
    root = Path(data_root).expanduser().resolve()
    candidates = (
        root / task / "test.jsonl",
        root / "ruler_data" / task / "test.jsonl",
    )
    found = [path for path in candidates if path.is_file()]
    if len(found) > 1:
        raise RuntimeError(f"Ambiguous RULER data for {task!r}: {[str(path) for path in found]}")
    if found:
        return found[0]
    raise FileNotFoundError(
        f"Pinned RULER-v1 task {task!r} was not found below {root}; expected "
        f"{candidates[0]} (NeMo-Skills setup roots should be passed directly)"
    )


def _load_manifest(
    data_root: str | Path,
    manifest_path: Optional[str | Path],
    tokenizer,
    tasks: Sequence[str],
) -> tuple[dict, Path, str, str]:
    """Load and validate the generation manifest for one length directory."""
    root = Path(data_root).expanduser().resolve()
    if manifest_path is not None:
        path = Path(manifest_path).expanduser().resolve()
        if not path.is_file():
            raise FileNotFoundError(f"RULER generation manifest not found: {path}")
    else:
        candidates = (root / "manifest.json", root.parent / "manifest.json")
        found = [candidate for candidate in candidates if candidate.is_file()]
        if len(found) != 1:
            raise FileNotFoundError(
                "Expected exactly one RULER generation manifest at "
                f"{candidates[0]} or {candidates[1]}, found {[str(item) for item in found]}"
            )
        path = found[0]
    try:
        with path.open(encoding="utf-8") as stream:
            manifest = json.load(stream)
    except json.JSONDecodeError as exc:
        raise ValueError(f"Invalid RULER generation manifest JSON: {path}") from exc
    if not isinstance(manifest, dict):
        raise ValueError(f"RULER generation manifest must be a JSON object: {path}")
    if manifest.get("schema_version") != 1:
        raise RuntimeError(
            f"Unsupported RULER manifest schema_version={manifest.get('schema_version')!r}"
        )
    if manifest.get("benchmark") != RULER_V1_PROTOCOL_LABEL:
        raise RuntimeError(f"Manifest is not for {RULER_V1_PROTOCOL_LABEL}: {path}")

    sources = manifest.get("sources", {})
    if sources.get("ruler_commit") != RULER_SOURCE_COMMIT:
        raise RuntimeError(
            f"Manifest RULER commit {sources.get('ruler_commit')!r} does not match "
            f"the audited protocol commit {RULER_SOURCE_COMMIT}"
        )
    if sources.get("nemo_skills_commit") != NEMO_SKILLS_RULER_SOURCE_COMMIT:
        raise RuntimeError(
            "Manifest NeMo-Skills commit "
            f"{sources.get('nemo_skills_commit')!r} does not match the audited "
            f"protocol commit {NEMO_SKILLS_RULER_SOURCE_COMMIT}"
        )

    protocol = manifest.get("protocol", {})
    if protocol.get("num_samples_per_task") != RULER_V1_SAMPLES_PER_TASK:
        raise RuntimeError(
            "RULER manifest must declare exactly " f"{RULER_V1_SAMPLES_PER_TASK} samples per task"
        )
    if protocol.get("prepare_for_nemo_skills") is not True:
        raise RuntimeError("RULER data must be generated with prepare_for_nemo_skills=true")
    if protocol.get("sampling_protocol") != RULER_V1_SAMPLING_PROTOCOL:
        raise RuntimeError(
            "RULER manifest sampling_protocol does not identify the pinned "
            "NeMo-Skills 100-sample/task adapter and canonical NVIDIA 500-sample/task "
            "reference"
        )
    manifest_tasks = protocol.get("tasks")
    if not isinstance(manifest_tasks, list) or not set(tasks).issubset(manifest_tasks):
        raise RuntimeError(
            f"RULER manifest task set does not contain all requested tasks: {list(tasks)}"
        )

    try:
        sequence_length = str(int(root.name))
    except ValueError as exc:
        raise ValueError(
            f"RULER data_root must be a numeric sequence-length directory, got {root}"
        ) from exc
    lengths = protocol.get("lengths")
    if not isinstance(lengths, list) or int(sequence_length) not in lengths:
        raise RuntimeError(f"RULER manifest does not declare sequence length {sequence_length}")
    file_group = manifest.get("files", {}).get(sequence_length)
    if not isinstance(file_group, dict) or not set(tasks).issubset(file_group):
        raise RuntimeError(
            f"RULER manifest has no complete file group for length {sequence_length}"
        )

    model_info = manifest.get("model", {})
    expected_model = model_info.get("path")
    actual_model = getattr(tokenizer, "name_or_path", None)
    if not isinstance(expected_model, str) or not expected_model:
        raise RuntimeError("RULER manifest is missing model.path")
    if not isinstance(actual_model, str) or not actual_model:
        raise RuntimeError("Tokenizer does not expose name_or_path for manifest validation")
    expected_path = Path(expected_model).expanduser()
    actual_path = Path(actual_model).expanduser()
    if expected_path.exists() and actual_path.exists():
        same_model = expected_path.resolve() == actual_path.resolve()
    else:
        same_model = expected_model == actual_model
    if not same_model:
        raise RuntimeError(
            f"RULER data were generated for tokenizer/model {expected_model}, "
            f"but evaluator loaded {actual_model}"
        )
    if expected_path.is_dir():
        for filename, metadata in model_info.get("metadata_files", {}).items():
            metadata_path = expected_path / filename
            if not metadata_path.is_file() or _sha256(metadata_path) != metadata.get("sha256"):
                raise RuntimeError(
                    f"RULER tokenizer/model metadata changed since generation: {metadata_path}"
                )
    return manifest, path, _sha256(path), sequence_length


def _validate_references(value, *, path: Path, line_number: int) -> tuple[str, ...]:
    if not isinstance(value, list) or not value:
        raise ValueError(f"{path}:{line_number}: expected a non-empty list of reference strings")
    references = tuple(value)
    if any(not isinstance(reference, str) or not reference for reference in references):
        raise ValueError(f"{path}:{line_number}: every RULER reference must be a non-empty string")
    return references


def load_ruler_v1_task(
    data_root: str | Path,
    task: str,
    *,
    expected_samples: int = RULER_V1_SAMPLES_PER_TASK,
) -> tuple[List[_RulerSample], Path, str, str]:
    """Load and strictly validate one generated RULER v1 task file.

    Both NVIDIA/RULER's raw schema (``input`` + ``answer_prefix`` +
    ``outputs``) and NeMo-Skills' lossless converted schema (``question`` +
    ``expected_answer``) are accepted. A file must contain the pinned adapter's
    100 rows even when the caller later selects a smoke subset. The pinned
    generator's random example identifiers are not guaranteed to be unique.
    """
    if task not in RULER_V1_TASKS:
        raise ValueError(f"Unknown RULER v1 task {task!r}")
    if (
        isinstance(expected_samples, bool)
        or not isinstance(expected_samples, int)
        or expected_samples <= 0
    ):
        raise ValueError("expected_samples must be a positive integer")

    path = _task_file(data_root, task)
    samples: List[_RulerSample] = []
    formats = set()
    with path.open(encoding="utf-8") as stream:
        for line_number, line in enumerate(stream, start=1):
            if not line.strip():
                raise ValueError(f"{path}:{line_number}: blank JSONL rows are not allowed")
            try:
                row = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"{path}:{line_number}: invalid JSON") from exc
            if not isinstance(row, dict):
                raise ValueError(f"{path}:{line_number}: expected a JSON object")

            if {"input", "answer_prefix", "outputs"}.issubset(row):
                if not isinstance(row["input"], str) or not isinstance(row["answer_prefix"], str):
                    raise ValueError(
                        f"{path}:{line_number}: input and answer_prefix must be strings"
                    )
                # This exact concatenation is what NVIDIA-NeMo/Skills'
                # prepare_task_for_ns writes to its `question` field.
                prompt = row["input"] + row["answer_prefix"]
                references = _validate_references(
                    row["outputs"], path=path, line_number=line_number
                )
                row_format = "nvidia_ruler_input_plus_answer_prefix"
            elif {"question", "expected_answer"}.issubset(row):
                if not isinstance(row["question"], str):
                    raise ValueError(f"{path}:{line_number}: question must be a string")
                prompt = row["question"]
                references = _validate_references(
                    row["expected_answer"], path=path, line_number=line_number
                )
                row_format = "nemo_skills_lossless_conversion"
            else:
                raise ValueError(
                    f"{path}:{line_number}: expected raw NVIDIA/RULER fields "
                    "{input, answer_prefix, outputs} or NeMo-Skills fields "
                    "{question, expected_answer}"
                )
            if not prompt:
                raise ValueError(f"{path}:{line_number}: released prompt is empty")

            index = row.get("index")
            length = row.get("length")
            if not isinstance(index, int) or isinstance(index, bool):
                raise ValueError(f"{path}:{line_number}: index must be an integer")
            if not isinstance(length, int) or isinstance(length, bool) or length <= 0:
                raise ValueError(f"{path}:{line_number}: length must be a positive integer")
            length_with_template = row.get("length_w_model_temp")
            if (
                row_format == "nvidia_ruler_input_plus_answer_prefix"
                and length_with_template is None
            ):
                raise ValueError(
                    f"{path}:{line_number}: raw prepare_for_nemo_skills data must "
                    "include length_w_model_temp"
                )
            if length_with_template is not None and (
                not isinstance(length_with_template, int)
                or isinstance(length_with_template, bool)
                or length_with_template <= 0
            ):
                raise ValueError(
                    f"{path}:{line_number}: length_w_model_temp must be a positive integer"
                )
            formats.add(row_format)
            samples.append(
                _RulerSample(
                    index=index,
                    prompt=prompt,
                    references=references,
                    released_length=length,
                    released_length_with_template=length_with_template,
                    row_format=row_format,
                )
            )

    if len(samples) != expected_samples:
        raise RuntimeError(
            f"Expected {expected_samples} pinned NeMo-Skills RULER v1 rows for {task}, "
            f"found {len(samples)} in {path}"
        )
    if len(formats) != 1:
        raise RuntimeError(f"RULER v1 task {task} mixes row schemas in {path}")
    return samples, path, _sha256(path), next(iter(formats))


def ruler_v1_sample_score(task: str, prediction: str, references: Sequence[str]) -> float:
    """Return NVIDIA's case-insensitive substring credit for one sample.

    NIAH, variable tracking, common-word extraction, and frequent-word
    extraction receive the fraction of *all* references present.  QA receives
    one point when *any* reference is present.  This mirrors the pinned
    NeMo-Skills ``match_type=all``/``part`` evaluator exactly.
    """
    if task not in RULER_V1_TASKS:
        raise ValueError(f"Unknown RULER v1 task {task!r}")
    if not references:
        raise ValueError("RULER references must be non-empty")
    if any(not isinstance(reference, str) or not reference for reference in references):
        raise ValueError("RULER references must contain non-empty strings")
    if not isinstance(prediction, str):
        raise TypeError("RULER prediction must be a string")
    lowered = prediction.lower()
    hits = [1.0 if reference.lower() in lowered else 0.0 for reference in references]
    if task.startswith("qa_"):
        return max(hits)
    return sum(hits) / len(hits)


def _model_context_limit(model) -> tuple[int, str]:
    config = model.config
    if hasattr(config, "get_text_config"):
        config = config.get_text_config()
        source = "model.config.get_text_config().max_position_embeddings"
    else:
        source = "model.config.max_position_embeddings"
    limit = getattr(config, "max_position_embeddings", None)
    if not isinstance(limit, int) or isinstance(limit, bool) or limit <= 0:
        raise ValueError(
            "Model config does not expose a positive max_position_embeddings; "
            "pass a model with an explicit context limit"
        )
    return limit, source


def _encode_prompt(tokenizer, prompt: str) -> tuple[torch.Tensor, str]:
    """Apply the paired model-native non-thinking one-user-message adaptation."""
    if getattr(tokenizer, "chat_template", None):
        messages = [{"role": "user", "content": prompt}]
        apply_template = getattr(tokenizer, "apply_chat_template", None)
        if not callable(apply_template):
            raise RuntimeError(
                "Tokenizer advertises a chat template but has no callable " "apply_chat_template"
            )
        try:
            encoded = apply_template(
                messages,
                add_generation_prompt=True,
                return_tensors="pt",
                return_dict=True,
                enable_thinking=False,
            )
        except TypeError as exc:
            # Qwen3 defaults to thinking mode, which is not suitable for RULER's
            # 32--128-token answer budgets.  Non-thinking models may reject this
            # keyword at the Python signature boundary.  Only that exact
            # incompatibility may fall back; all rendering failures are fatal.
            message = str(exc).lower()
            unsupported_thinking_kwarg = "enable_thinking" in message and (
                "unexpected keyword" in message
                or "unexpected argument" in message
                or "keyword argument" in message
            )
            if not unsupported_thinking_kwarg:
                raise RuntimeError(
                    "Tokenizer chat template failed for the RULER paired " "non-thinking wrapper"
                ) from exc
            try:
                encoded = apply_template(
                    messages,
                    add_generation_prompt=True,
                    return_tensors="pt",
                    return_dict=True,
                )
            except Exception as fallback_exc:
                raise RuntimeError(
                    "Tokenizer chat template failed for the RULER paired wrapper"
                ) from fallback_exc
        except Exception as exc:
            raise RuntimeError(
                "Tokenizer advertises a chat template but failed to encode the "
                "RULER paired non-thinking user message"
            ) from exc
        wrapper = (
            "generic user message; tokenizer.apply_chat_template with "
            "enable_thinking=false when supported"
        )
        if isinstance(encoded, dict):
            ids = encoded["input_ids"]
        elif hasattr(encoded, "input_ids"):
            ids = encoded.input_ids
        else:
            ids = encoded
    else:
        ids = tokenizer(prompt, return_tensors="pt", truncation=False).input_ids
        wrapper = "base/raw released prompt (tokenizer has no chat template)"
    if not isinstance(ids, torch.Tensor) or ids.ndim != 2 or ids.shape[0] != 1:
        raise TypeError("Tokenizer must return input_ids with shape [1, sequence_length]")
    if ids.shape[1] == 0:
        raise ValueError("Tokenizer returned an empty RULER prompt")
    return ids, wrapper


def _mean_stderr(values: Sequence[float]) -> float:
    return statistics.stdev(values) / math.sqrt(len(values)) if len(values) > 1 else 0.0


def _token_summary(values: Sequence[int]) -> dict:
    return {
        "min": min(values),
        "median": round(float(statistics.median(values)), 1),
        "max": max(values),
    }


@dataclass
class RulerV1Result:
    tasks: List[str]
    n: int
    score: float  # pinned 13-task macro, in percentage points
    per_task: Dict[str, dict]
    dataset_files: Dict[str, dict]
    input_tokens: Dict[str, dict]
    max_context_tokens: int
    model_max_position_embeddings: int
    model_context_source: str
    max_observed_prompt_tokens: int
    max_observed_prompt_plus_max_generation_tokens: int
    max_observed_generated_tokens: int
    task_accuracy_sum: float
    generation_eos_token_ids: List[int]
    generation_eos_token_id_source: str
    start: int = 0
    limit_per_task: Optional[int] = None
    mem_fraction: float = 1.0
    mem_fraction_aggregation: str = "fullkv_no_cache"
    prompt_wrappers: List[str] = field(default_factory=list)
    per_example: Dict[str, List[dict]] = field(default_factory=dict)
    tokenizer_name_or_path: Optional[str] = None
    chat_template_sha256: Optional[str] = None
    generation_manifest: Dict[str, object] = field(default_factory=dict)
    generation_manifest_path: Optional[str] = None
    generation_manifest_sha256: Optional[str] = None
    sequence_length: Optional[int] = None
    compression_sufficient_statistics: Dict[str, object] = field(default_factory=dict)

    @property
    def protocol_complete(self) -> bool:
        return (
            tuple(self.tasks) == RULER_V1_TASKS
            and self.start == 0
            and self.limit_per_task is None
            and self.n == len(RULER_V1_TASKS) * RULER_V1_SAMPLES_PER_TASK
            and all(
                self.per_task[task]["n"] == RULER_V1_SAMPLES_PER_TASK for task in RULER_V1_TASKS
            )
        )

    def as_dict(self) -> dict:
        combined = hashlib.sha256(
            "".join(
                f"{task}:{self.dataset_files[task]['sha256']}\n"
                for task in sorted(self.dataset_files)
            ).encode("utf-8")
        ).hexdigest()
        return {
            "schema_version": RULER_V1_RESULT_SCHEMA_VERSION,
            "benchmark": RULER_V1_PROTOCOL_LABEL,
            "metric": (
                "13-task macro accuracy"
                if self.protocol_complete
                else "task-subset macro accuracy"
            ),
            "score": round(self.score, 4),
            "accuracy": round(self.score / 100.0, 6),
            "score_sufficient_statistics": {
                "task_accuracy_sum": round(self.task_accuracy_sum, 10),
                "task_count": len(self.tasks),
            },
            "n": self.n,
            "tasks": list(self.tasks),
            "per_task": self.per_task,
            "mem_fraction": round(self.mem_fraction, 6),
            "mem_fraction_aggregation": self.mem_fraction_aggregation,
            "example_cache_lifetime": PER_EXAMPLE_CACHE_LIFETIME,
            "cross_iteration_tensor_retention": (
                PER_EXAMPLE_CROSS_ITERATION_TENSOR_RETENTION
            ),
            "start": self.start,
            "limit_per_task": self.limit_per_task,
            "samples_per_task": RULER_V1_SAMPLES_PER_TASK,
            "sampling_protocol": RULER_V1_SAMPLING_PROTOCOL,
            "protocol_complete": self.protocol_complete,
            "canonical_nvidia_samples_per_task": (RULER_V1_CANONICAL_NVIDIA_SAMPLES_PER_TASK),
            "canonical_nvidia_full_eval": False,
            "protocol_scope": RULER_V1_PROTOCOL_SCOPE,
            "reference_model_wrapper_exact": False,
            "evaluation_scope": (
                "complete_nemo_skills_ruler_v1_100_sample_per_task_data_tasks_"
                "and_scorer_with_"
                "paired_decoder_adaptation"
                if self.protocol_complete
                else "subset_or_smoke_with_paired_decoder_adaptation"
            ),
            "input_tokens": self.input_tokens,
            "max_context_tokens": self.max_context_tokens,
            "model_context": {
                "source": self.model_context_source,
                "max_position_embeddings": self.model_max_position_embeddings,
                "named_ruler_sequence_limit": self.max_context_tokens,
                "max_observed_prompt_tokens": self.max_observed_prompt_tokens,
                "max_observed_prompt_plus_max_generation_tokens": (
                    self.max_observed_prompt_plus_max_generation_tokens
                ),
                "max_observed_generated_tokens": self.max_observed_generated_tokens,
                "capacity_check": (
                    "input_tokens + pinned upstream task max_new_tokens <= named RULER "
                    "sequence length <= max_position_embeddings"
                ),
            },
            "dataset_files": self.dataset_files,
            "combined_dataset_sha256": combined,
            "generation_manifest": {
                "path": self.generation_manifest_path,
                "sha256": self.generation_manifest_sha256,
                "content": self.generation_manifest,
            },
            "protocol": {
                "ruler_repository": "https://github.com/NVIDIA/RULER",
                "ruler_source_commit": RULER_SOURCE_COMMIT,
                "nemo_skills_repository": "https://github.com/NVIDIA-NeMo/Skills",
                "nemo_skills_source_commit": NEMO_SKILLS_RULER_SOURCE_COMMIT,
                "task_set": "RULER v1 13-task synthetic setup",
                "sampling_protocol": RULER_V1_SAMPLING_PROTOCOL,
                "sequence_length": self.sequence_length,
                "prompt": "released input + answer_prefix, verbatim, as sole generic user message",
                "prompt_wrappers": list(self.prompt_wrappers),
                "chat_template_kwargs": dict(RULER_V1_CHAT_TEMPLATE_KWARGS),
                "tokenizer_name_or_path": self.tokenizer_name_or_path,
                "chat_template_sha256": self.chat_template_sha256,
                "generation": (
                    "greedy; pinned upstream task-specific max_new_tokens; model-aware "
                    "non-thinking chat-wrapper adaptation"
                ),
                "max_new_tokens": dict(RULER_V1_MAX_NEW_TOKENS),
                "eos_token_ids": list(self.generation_eos_token_ids),
                "eos_token_id_source": self.generation_eos_token_id_source,
                "stop_conditions": [
                    "any_generation_config_eos_token_id",
                    "max_new_tokens",
                ],
                "scoring": (
                    "case-insensitive substring; all-reference fraction for "
                    "niah/vt/cwe/fwe, max-reference match for qa"
                ),
                "truncation": "none; context overflow is fatal",
                "context_semantics": (
                    "named RULER sequence length is the total prompt-plus-generation "
                    "limit; actual prompt + pinned upstream task max_new_tokens is checked "
                    "against both the named limit and model capacity"
                ),
            },
            "per_example": self.per_example,
            "compression_sufficient_statistics": self.compression_sufficient_statistics,
        }


@torch.no_grad()
def ruler_v1(
    model,
    tokenizer,
    data_root: str | Path,
    manifest_path: Optional[str | Path] = None,
    cache_factory: Optional[Callable[[], object]] = None,
    tasks: Optional[Sequence[str]] = None,
    max_context_tokens: Optional[int] = None,
    start: int = 0,
    limit_per_task: Optional[int] = None,
    evict: bool = False,
    attn_capture: bool = False,
) -> RulerV1Result:
    """Evaluate the pinned NeMo-Skills RULER-v1 100/task data without truncation.

    A finite ``limit_per_task``, non-zero ``start``, or task subset is useful for
    smoke/recovery runs but is explicitly labelled incomplete.  The underlying
    files must still contain all 100 examples per task from this pinned adapter
    protocol.  This protocol is not the canonical NVIDIA 500-sample/task run.
    """
    from transformers import DynamicCache

    selected_tasks = list(tasks) if tasks is not None else list(RULER_V1_TASKS)
    if not selected_tasks:
        raise ValueError("At least one RULER v1 task is required")
    if len(set(selected_tasks)) != len(selected_tasks):
        raise ValueError(f"Duplicate RULER v1 tasks: {selected_tasks}")
    unknown = set(selected_tasks) - set(RULER_V1_TASKS)
    if unknown:
        raise ValueError(f"Unknown RULER v1 task(s): {sorted(unknown)}")
    # Canonical order makes the macro and combined hash stable across callers.
    selected_tasks = [task for task in RULER_V1_TASKS if task in selected_tasks]
    if isinstance(start, bool) or not isinstance(start, int) or start < 0:
        raise ValueError("start must be a non-negative integer")
    if limit_per_task is not None and (
        isinstance(limit_per_task, bool)
        or not isinstance(limit_per_task, int)
        or limit_per_task <= 0
    ):
        raise ValueError("limit_per_task must be a positive integer or None")
    if not isinstance(evict, bool) or not isinstance(attn_capture, bool):
        raise ValueError("evict and attn_capture must be bools")

    manifest, resolved_manifest, manifest_digest, sequence_length_text = _load_manifest(
        data_root,
        manifest_path,
        tokenizer,
        selected_tasks,
    )
    sequence_length = int(sequence_length_text)
    advertised_limit, context_limit_source = _model_context_limit(model)
    # NVIDIA's generators define max_seq_length as the total of all input and
    # generated tokens.  NeMo preparation also reserves chat-template tokens,
    # while each task generator reserves its task-specific output allowance.
    # Re-tokenization is checked below because the actually applied model
    # template, rather than an estimated reserve, is the authoritative length.
    sequence_limit = sequence_length if max_context_tokens is None else max_context_tokens
    if (
        not isinstance(sequence_limit, int)
        or isinstance(sequence_limit, bool)
        or sequence_limit <= 0
    ):
        raise ValueError("max_context_tokens must be a positive integer or None")
    if sequence_limit > advertised_limit:
        raise ValueError(
            f"Declared RULER sequence limit {sequence_limit} exceeds the model's "
            f"max_position_embeddings={advertised_limit}"
        )
    if sequence_limit != sequence_length:
        raise ValueError(
            f"Declared RULER sequence limit {sequence_limit} does not match the generated "
            f"sequence-length directory {sequence_length}. Use tokenizer-specific data "
            "generated for the exact evaluated length."
        )

    eos_token_ids, eos_token_id_source = effective_generation_eos_token_ids(model, tokenizer)
    per_task: Dict[str, dict] = {}
    dataset_files: Dict[str, dict] = {}
    input_tokens: Dict[str, dict] = {}
    records: Dict[str, List[dict]] = {}
    wrappers = set()
    all_mem: List[float] = []
    total_n = 0
    task_means: Dict[str, float] = {}
    observed_prompt_plus_max_generation: List[int] = []
    observed_generated_tokens: List[int] = []

    manifest_file_group = manifest["files"][sequence_length_text]

    for task in selected_tasks:
        samples, path, digest, row_format = load_ruler_v1_task(data_root, task)
        manifest_file = manifest_file_group[task]
        if manifest_file.get("rows") != len(samples) or manifest_file.get("sha256") != digest:
            raise RuntimeError(f"RULER data file does not match its generation manifest: {path}")
        released_template_lengths = [
            sample.released_length_with_template
            for sample in samples
            if sample.released_length_with_template is not None
        ]
        if released_template_lengths and (
            manifest_file.get("length_w_model_temp_min") != min(released_template_lengths)
            or manifest_file.get("length_w_model_temp_max") != max(released_template_lengths)
        ):
            raise RuntimeError(
                f"RULER released length metadata does not match its manifest: {path}"
            )
        chosen = (
            samples[start:] if limit_per_task is None else samples[start : start + limit_per_task]
        )
        if not chosen:
            raise ValueError(
                f"RULER v1 {task} selection is empty "
                f"(start={start}, limit_per_task={limit_per_task})"
            )
        task_scores: List[float] = []
        task_tokens: List[int] = []
        task_mem: List[float] = []
        task_records: List[dict] = []
        max_new_tokens = RULER_V1_MAX_NEW_TOKENS[task]

        for row_position, sample in enumerate(chosen, start=start):
            ids, wrapper = _encode_prompt(tokenizer, sample.prompt)
            wrappers.add(wrapper)
            input_length = int(ids.shape[1])
            if (
                sample.released_length_with_template is not None
                and sample.released_length_with_template > int(sequence_length_text)
            ):
                raise RuntimeError(
                    f"RULER v1 {task} index {sample.index} has released "
                    f"length_w_model_temp={sample.released_length_with_template}, exceeding "
                    f"its generated sequence length {sequence_length_text}"
                )
            if input_length + max_new_tokens > sequence_limit:
                raise RuntimeError(
                    f"RULER v1 {task} index {sample.index} needs at most {input_length} "
                    f"prompt + {max_new_tokens} generation tokens, exceeding the named "
                    f"RULER sequence limit {sequence_limit}. Refusing benchmark-changing "
                    "truncation or generation-budget reduction."
                )
            if input_length + max_new_tokens > advertised_limit:
                raise RuntimeError(
                    f"RULER v1 {task} index {sample.index} needs at most {input_length} "
                    f"prompt + {max_new_tokens} generation tokens, exceeding the model's "
                    f"max_position_embeddings={advertised_limit}. Refusing "
                    "benchmark-changing truncation."
                )
            cache = (
                cache_factory() if cache_factory is not None else DynamicCache(config=model.config)
            )
            post_step = (lambda value: value.evict_now()) if evict else None
            generated = greedy_answer(
                model,
                ids,
                cache,
                max_new_tokens=max_new_tokens,
                post_prefill=post_step,
                eos=eos_token_ids,
                attn_capture=attn_capture,
            )
            compression = cache_compression_sufficient_statistics(cache)
            if not isinstance(generated, torch.Tensor) or generated.ndim != 2:
                raise TypeError("RULER greedy generation must return a rank-2 token tensor")
            generated_tokens = int(generated.shape[1])
            if generated_tokens <= 0 or generated_tokens > max_new_tokens:
                raise RuntimeError(
                    f"RULER v1 {task} index {sample.index} generated {generated_tokens} "
                    f"tokens with max_new_tokens={max_new_tokens}"
                )
            prediction = tokenizer.decode(generated[0], skip_special_tokens=True)
            sample_score = ruler_v1_sample_score(task, prediction, sample.references)
            task_scores.append(sample_score)
            task_tokens.append(input_length)
            observed_prompt_plus_max_generation.append(input_length + max_new_tokens)
            observed_generated_tokens.append(generated_tokens)
            fraction = cache_mem_fraction(cache)
            if fraction is not None:
                task_mem.append(fraction)
            task_records.append(
                {
                    "row_position": row_position,
                    "index": sample.index,
                    "released_length": sample.released_length,
                    "released_length_with_template": sample.released_length_with_template,
                    "input_tokens": input_length,
                    "generated_tokens": generated_tokens,
                    "max_new_tokens": max_new_tokens,
                    "stop_token_ids": list(eos_token_ids),
                    "prompt_truncated": False,
                    "prediction": prediction,
                    "references": list(sample.references),
                    "credit": round(sample_score, 6),
                    **compression,
                }
            )
            # All retained records above are host scalars/strings.  Release the
            # complete cache and generation tensors before the next factory
            # call; RHS-before-rebind would otherwise create a two-cache peak.
            del cache, generated, ids

        accuracy = sum(task_scores) / len(task_scores)
        task_means[task] = accuracy
        stderr = _mean_stderr(task_scores)
        task_compression = aggregate_compression_sufficient_statistics(task_records)
        task_mem_fraction, task_mem_aggregation = aggregate_mem_fraction(
            task_compression, task_mem
        )
        per_task[task] = {
            "n": len(task_scores),
            "credit_sum": round(math.fsum(task_scores), 10),
            "score": round(100.0 * accuracy, 4),
            "accuracy": round(accuracy, 6),
            "accuracy_stderr": round(stderr, 6),
            "max_new_tokens": max_new_tokens,
            "mem_fraction": round(task_mem_fraction, 6),
            "mem_fraction_aggregation": task_mem_aggregation,
            "compression_sufficient_statistics": task_compression,
        }
        dataset_files[task] = {
            "path": str(path),
            "sha256": digest,
            "rows": len(samples),
            "row_format": row_format,
        }
        input_tokens[task] = _token_summary(task_tokens)
        records[task] = task_records
        all_mem.extend(task_mem)
        total_n += len(task_scores)
        print(
            f"    [RULER v1] {task}: {100.0 * accuracy:.2f} " f"(n={len(task_scores)})",
            flush=True,
        )

    macro = sum(task_means.values()) / len(task_means)
    macro_numerator = math.fsum(task_means.values())
    chat_template = getattr(tokenizer, "chat_template", None)
    all_records = [record for task in selected_tasks for record in records[task]]
    compression_statistics = aggregate_compression_sufficient_statistics(all_records)
    aggregate_fraction, fraction_aggregation = aggregate_mem_fraction(
        compression_statistics, all_mem
    )
    result = RulerV1Result(
        tasks=selected_tasks,
        n=total_n,
        score=100.0 * macro,
        per_task=per_task,
        dataset_files=dataset_files,
        input_tokens=input_tokens,
        max_context_tokens=sequence_limit,
        model_max_position_embeddings=advertised_limit,
        model_context_source=context_limit_source,
        max_observed_prompt_tokens=max(summary["max"] for summary in input_tokens.values()),
        max_observed_prompt_plus_max_generation_tokens=max(observed_prompt_plus_max_generation),
        max_observed_generated_tokens=max(observed_generated_tokens),
        task_accuracy_sum=macro_numerator,
        generation_eos_token_ids=eos_token_ids,
        generation_eos_token_id_source=eos_token_id_source,
        start=start,
        limit_per_task=limit_per_task,
        mem_fraction=aggregate_fraction,
        mem_fraction_aggregation=fraction_aggregation,
        prompt_wrappers=sorted(wrappers),
        per_example=records,
        tokenizer_name_or_path=getattr(tokenizer, "name_or_path", None),
        chat_template_sha256=(
            hashlib.sha256(chat_template.encode("utf-8")).hexdigest()
            if isinstance(chat_template, str)
            else None
        ),
        generation_manifest=manifest,
        generation_manifest_path=str(resolved_manifest),
        generation_manifest_sha256=manifest_digest,
        sequence_length=int(sequence_length_text),
        compression_sufficient_statistics=compression_statistics,
    )
    return result
